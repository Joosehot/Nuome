//! A function that builds graphs: Nuome searches for strongly regular
//! graphs srg(v, k, λ, μ) written as one formula,
//!
//!   x ~ y  exactly when  x - y ∈ S,  S = a union of orbits of a multiplier group T,
//!
//! on an abelian group G of order v (a Cayley graph; T acts by x ↦ t·x for
//! units t of the exponent of G). Almost every known strongly regular graph
//! with a regular abelian symmetry is of this form (Paley, rook's graphs,
//! Clebsch, Brouwer-Haemers, Berlekamp-van Lint-Seidel).
//!
//! The search is exact: S is a partial difference set exactly when every
//! nontrivial character χ of G takes χ(S) ∈ {r, s}, the two eigenvalues.
//! Characters are constant on T-orbits, so the condition is one linear
//! equation a character orbit over 0/1 choices of the T-orbits, solved by
//! depth-first search with bounds. Every graph found is checked from scratch
//! (every vertex x: |S ∩ (x - S)| = λ if x ∈ S, μ if not) before anything
//! is said. A search that finds nothing proves only what it covered: no
//! such S for the groups and multiplier groups tried.

use std::f64::consts::PI;

/// An abelian group Z_{d1} x ... x Z_{dr}; elements by mixed-radix index.
#[derive(Clone, Debug)]
pub struct Group {
    pub dims: Vec<u64>,
    pub order: u64,
    pub exponent: u64,
}

fn gcd(a: u64, b: u64) -> u64 {
    if b == 0 {
        a
    } else {
        gcd(b, a % b)
    }
}

impl Group {
    pub fn new(dims: Vec<u64>) -> Group {
        let order = dims.iter().product();
        let exponent = dims.iter().fold(1, |l, &d| l / gcd(l, d) * d);
        Group { dims, order, exponent }
    }
    fn coords(&self, mut i: u64) -> Vec<u64> {
        self.dims
            .iter()
            .map(|&d| {
                let c = i % d;
                i /= d;
                c
            })
            .collect()
    }
    fn index(&self, c: &[u64]) -> u64 {
        let mut i = 0;
        for (j, &d) in self.dims.iter().enumerate().rev() {
            i = i * d + c[j];
        }
        i
    }
    fn mul(&self, t: u64, i: u64) -> u64 {
        let c: Vec<u64> = self.coords(i).iter().zip(&self.dims).map(|(&x, &d)| x * (t % d) % d).collect();
        self.index(&c)
    }
    pub fn sub(&self, a: u64, b: u64) -> u64 {
        let (x, y) = (self.coords(a), self.coords(b));
        let c: Vec<u64> = x.iter().zip(&y).zip(&self.dims).map(|((&p, &q), &d)| (p + d - q) % d).collect();
        self.index(&c)
    }
    pub fn name(&self) -> String {
        self.dims.iter().map(|d| format!("Z{d}")).collect::<Vec<_>>().join("xZ").replace("xZZ", "xZ")
    }
}

fn factor(mut n: u64) -> Vec<(u64, u32)> {
    let mut out = Vec::new();
    let mut p = 2;
    while p * p <= n {
        let mut e = 0;
        while n % p == 0 {
            n /= p;
            e += 1;
        }
        if e > 0 {
            out.push((p, e));
        }
        p += 1;
    }
    if n > 1 {
        out.push((n, 1));
    }
    out
}

fn partitions(n: u32, max: u32) -> Vec<Vec<u32>> {
    if n == 0 {
        return vec![vec![]];
    }
    let mut out = Vec::new();
    for first in (1..=n.min(max)).rev() {
        for mut rest in partitions(n - first, first) {
            rest.insert(0, first);
            out.push(rest);
        }
    }
    out
}

/// Every abelian group of order v, by its elementary divisors.
pub fn abelian_groups(v: u64) -> Vec<Group> {
    let mut gs: Vec<Vec<u64>> = vec![vec![]];
    for (p, e) in factor(v) {
        let mut next = Vec::new();
        for part in partitions(e, e) {
            for g in &gs {
                let mut g = g.clone();
                g.extend(part.iter().map(|&b| p.pow(b)));
                next.push(g);
            }
        }
        gs = next;
    }
    gs.into_iter().map(Group::new).collect()
}

/// The multiplier group generated by t and -1 (units mod the exponent).
fn multiplier_group(e: u64, t: u64) -> Vec<u64> {
    let mut seen = vec![false; e as usize];
    let mut set = vec![1 % e.max(1)];
    seen[set[0] as usize] = true;
    let gens = [t % e, (e - 1) % e];
    let mut i = 0;
    while i < set.len() {
        for &g in &gens {
            let x = set[i] * g % e;
            if !seen[x as usize] {
                seen[x as usize] = true;
                set.push(x);
            }
        }
        i += 1;
    }
    set.sort();
    set
}

/// The orbits of T on G minus 0, and on the characters (as group elements).
fn orbits(g: &Group, t: &[u64]) -> Vec<Vec<u64>> {
    let mut seen = vec![false; g.order as usize];
    seen[0] = true;
    let mut out = Vec::new();
    for x in 1..g.order {
        if seen[x as usize] {
            continue;
        }
        let mut orb = Vec::new();
        for &m in t {
            let y = g.mul(m, x);
            if !seen[y as usize] {
                seen[y as usize] = true;
                orb.push(y);
            }
        }
        out.push(orb);
    }
    out
}

/// Re χ_a(x) = cos(2π Σ a_j x_j / d_j).
fn chi(g: &Group, a: &[u64], x: &[u64]) -> f64 {
    let mut phase = 0.0;
    for j in 0..g.dims.len() {
        phase += (a[j] * x[j] % g.dims[j]) as f64 / g.dims[j] as f64;
    }
    (2.0 * PI * phase).cos()
}

pub struct Found {
    pub group: Group,
    /// how S was written: the multiplier group or the field's cyclotomic classes
    pub how: String,
    pub set: Vec<u64>,
    pub orbits_used: usize,
    pub orbits_total: usize,
}

/// Is the Cayley graph Cay(G, S) an srg(v, k, λ, μ)? Checked at every vertex x.
pub fn check_cayley(g: &Group, s: &[u64], k: u64, lambda: u64, mu: u64) -> bool {
    let mut ins = vec![false; g.order as usize];
    for &x in s {
        ins[x as usize] = true;
    }
    if s.len() as u64 != k || ins[0] || s.iter().any(|&x| !ins[g.sub(0, x) as usize]) {
        return false;
    }
    for x in 1..g.order {
        let c = s.iter().filter(|&&y| ins[g.sub(x, y) as usize]).count() as u64;
        if c != if ins[x as usize] { lambda } else { mu } {
            return false;
        }
    }
    true
}

struct Dfs<'a> {
    sizes: &'a [u64],
    /// w[c][i]: character orbit c on T-orbit i
    w: &'a [Vec<f64>],
    /// the remaining least and most each character orbit can still gain from orbit i on
    rest_min: Vec<Vec<f64>>,
    rest_max: Vec<Vec<f64>>,
    rest_size: Vec<u64>,
    targets: [f64; 2],
    k: u64,
    nodes: u64,
    budget: u64,
    chosen: Vec<usize>,
}

impl<'a> Dfs<'a> {
    fn fits(&self, sums: &[f64], i: usize) -> bool {
        sums.iter().enumerate().all(|(c, &s)| self.targets.iter().any(|&t| t >= s + self.rest_min[c][i] - 1e-6 && t <= s + self.rest_max[c][i] + 1e-6))
    }
    fn go(&mut self, i: usize, size: u64, sums: &mut Vec<f64>) -> bool {
        self.nodes += 1;
        if self.nodes > self.budget {
            return false;
        }
        if size == self.k {
            return sums.iter().all(|&s| self.targets.iter().any(|&t| (s - t).abs() < 1e-6));
        }
        if i == self.sizes.len() || size + self.rest_size[i] < self.k || !self.fits(sums, i) {
            return false;
        }
        // take orbit i
        if size + self.sizes[i] <= self.k {
            for c in 0..sums.len() {
                sums[c] += self.w[c][i];
            }
            self.chosen.push(i);
            if self.go(i + 1, size + self.sizes[i], sums) {
                return true;
            }
            self.chosen.pop();
            for c in 0..sums.len() {
                sums[c] -= self.w[c][i];
            }
        }
        // leave it
        self.go(i + 1, size, sums)
    }
}

/// One group, one set of orbits: an S that makes an srg. The constraints
/// are the characters `char_reps` (one a class of characters equal on every
/// orbit). Returns the graph if found and checked, and whether the search
/// was exhausted (false when it stopped at the node budget).
fn search_orbits(g: &Group, orbs: Vec<Vec<u64>>, char_reps: &[u64], how: String, k: u64, lambda: u64, mu: u64, budget: u64) -> (Option<Found>, bool) {
    let disc = ((lambda as f64 - mu as f64).powi(2) + 4.0 * (k as f64 - mu as f64)).sqrt();
    let r = ((lambda as f64 - mu as f64) + disc) / 2.0;
    let s = ((lambda as f64 - mu as f64) - disc) / 2.0;
    let mut orbs = orbs;
    orbs.sort_by_key(|o| std::cmp::Reverse(o.len()));
    let sizes: Vec<u64> = orbs.iter().map(|o| o.len() as u64).collect();
    let coords: Vec<Vec<u64>> = (0..g.order).map(|i| g.coords(i)).collect();
    let mut w: Vec<Vec<f64>> = char_reps
        .iter()
        .map(|&a| {
            let a = &coords[a as usize];
            orbs.iter().map(|o| o.iter().map(|&x| chi(g, a, &coords[x as usize])).sum()).collect()
        })
        .collect();
    // one constraint a distinct row
    let mut keys = std::collections::HashSet::new();
    w.retain(|row| keys.insert(row.iter().map(|x| (x * 1e6).round() as i64).collect::<Vec<_>>()));
    let n = orbs.len();
    let mut rest_min = vec![vec![0.0; n + 1]; w.len()];
    let mut rest_max = vec![vec![0.0; n + 1]; w.len()];
    for c in 0..w.len() {
        for i in (0..n).rev() {
            rest_min[c][i] = rest_min[c][i + 1] + w[c][i].min(0.0);
            rest_max[c][i] = rest_max[c][i + 1] + w[c][i].max(0.0);
        }
    }
    let mut rest_size = vec![0; n + 1];
    for i in (0..n).rev() {
        rest_size[i] = rest_size[i + 1] + sizes[i];
    }
    let mut d = Dfs { sizes: &sizes, w: &w, rest_min, rest_max, rest_size, targets: [r, s], k, nodes: 0, budget, chosen: Vec::new() };
    let mut sums = vec![0.0; w.len()];
    let hit = d.go(0, 0, &mut sums);
    let exhausted = !hit && d.nodes <= budget;
    if hit {
        let set: Vec<u64> = d.chosen.iter().flat_map(|&i| orbs[i].clone()).collect();
        if check_cayley(g, &set, k, lambda, mu) {
            return (Some(Found { group: g.clone(), how, set, orbits_used: d.chosen.len(), orbits_total: n }), false);
        }
    }
    (None, exhausted)
}

/// GF(p^n) on the group Z_p^n: the powers of a primitive element, as group
/// indices (coordinates = coefficients of a primitive polynomial's residues).
fn field_powers(p: u64, n: usize) -> Option<Vec<u64>> {
    let q = p.pow(n as u32);
    let g = Group::new(vec![p; n]);
    // monic f = x^n + c_{n-1} x^{n-1} + ... + c_0, by its low coefficients
    for low in 0..q {
        let c = g.coords(low);
        if c[0] == 0 {
            continue;
        }
        let times_x = |e: u64| -> u64 {
            let a = g.coords(e);
            let top = a[n - 1];
            let mut b = vec![0u64; n];
            for j in (1..n).rev() {
                b[j] = a[j - 1];
            }
            // x^n = -(c_{n-1} x^{n-1} + ... + c_0)
            for j in 0..n {
                b[j] = (b[j] + (p - c[j] % p) * top) % p;
            }
            g.index(&b)
        };
        let mut pw = vec![1u64];
        let mut e = times_x(1);
        while e != 1 && (pw.len() as u64) < q {
            pw.push(e);
            e = times_x(e);
        }
        if pw.len() as u64 == q - 1 {
            return Some(pw);
        }
    }
    None
}

pub struct Tried {
    pub group: String,
    pub searched: usize,
    pub exhausted: usize,
}

/// Every abelian group of order v; on each, the multiplier groups <t, -1>
/// (largest first, at most `max_t`), and on Z_p^n also the field's
/// cyclotomic classes; a node budget each.
pub fn search(v: u64, k: u64, lambda: u64, mu: u64, budget: u64, max_t: usize, seconds: f64) -> (Option<Found>, Vec<Tried>) {
    let t0 = std::time::Instant::now();
    let mut tried = Vec::new();
    for g in abelian_groups(v) {
        let (mut n, mut exhausted) = (0, 0);
        // the field GF(p^n) when G = Z_p^n: S a union of cosets of the subgroup of index d of GF(q)*
        let p = g.dims[0];
        if g.dims.len() >= 2 && g.dims.iter().all(|&d| d == p) && factor(p).len() == 1 && factor(p)[0].1 == 1 {
            if let Some(pw) = field_powers(p, g.dims.len()) {
                let q1 = v - 1;
                for d in (1..=q1).filter(|d| q1 % d == 0 && (p == 2 || (q1 / 2) % d == 0)) {
                    if t0.elapsed().as_secs_f64() > seconds {
                        break;
                    }
                    let orbs: Vec<Vec<u64>> = (0..d).map(|j| (0..q1 / d).map(|m| pw[(j + d * m) as usize]).collect()).collect();
                    if orbs.len() > 64 {
                        continue;
                    }
                    let reps: Vec<u64> = (1..v).collect();
                    n += 1;
                    let (f, ex) = search_orbits(&g, orbs, &reps, format!("GF({v}): S a union of cosets of the {}th powers", d), k, lambda, mu, budget);
                    if let Some(f) = f {
                        tried.push(Tried { group: g.name(), searched: n, exhausted });
                        return (Some(f), tried);
                    }
                    exhausted += ex as usize;
                }
            }
        }
        let e = g.exponent;
        let mut ts: Vec<(u64, Vec<u64>)> = Vec::new();
        let mut known = std::collections::HashSet::new();
        for t in 1..e.max(2) {
            if gcd(t, e) != 1 {
                continue;
            }
            let m = multiplier_group(e, t);
            if known.insert(m.clone()) {
                ts.push((t, m));
            }
        }
        // large multiplier groups make few orbits: try them first
        ts.sort_by_key(|(_, m)| std::cmp::Reverse(m.len()));
        for (gen, m) in ts.iter().take(max_t) {
            if t0.elapsed().as_secs_f64() > seconds {
                break;
            }
            n += 1;
            let orbs = orbits(&g, m);
            let reps: Vec<u64> = orbs.iter().map(|o| o[0]).collect();
            let (f, ex) = search_orbits(&g, orbs, &reps, format!("T = <{gen}, -1> ({} multipliers)", m.len()), k, lambda, mu, budget);
            if let Some(f) = f {
                tried.push(Tried { group: g.name(), searched: n, exhausted });
                return (Some(f), tried);
            }
            exhausted += ex as usize;
        }
        tried.push(Tried { group: g.name(), searched: n, exhausted });
    }
    (None, tried)
}

/// The known graphs the function must find again, then the open ones.
pub const KNOWN: &[(u64, u64, u64, u64, &str)] = &[
    (9, 4, 1, 2, "3 x 3 rook's graph (Conway's family)"),
    (13, 6, 2, 3, "Paley graph on 13"),
    (16, 5, 0, 2, "Clebsch graph"),
    (16, 6, 2, 2, "4 x 4 rook's graph / Shrikhande"),
    (25, 12, 5, 6, "Paley graph on 25"),
    (29, 14, 6, 7, "Paley graph on 29"),
    (49, 12, 5, 2, "7 x 7 rook's graph"),
    (64, 18, 2, 6, "a Cayley graph on Z2^6"),
    (81, 20, 1, 6, "Brouwer-Haemers graph"),
    (243, 22, 1, 2, "Berlekamp-van Lint-Seidel graph (Conway's family)"),
];

pub fn report(targets: &[(u64, u64, u64, u64)], seconds: f64) -> String {
    let mut out = String::from("The graph function: x ~ y when x - y is in S, S a union of multiplier orbits on an abelian group; every hit checked at every vertex\n\nfinding the known graphs again:\n");
    for &(v, k, l, m, name) in KNOWN {
        let t0 = std::time::Instant::now();
        let (f, _) = search(v, k, l, m, 20_000_000, 60, seconds);
        match f {
            Some(f) => out.push_str(&format!(
                "  srg({v},{k},{l},{m}) {name}: FOUND on {}, {}, S = {} of {} orbits, checked ({:.2} s)\n",
                f.group.name(),
                f.how,
                f.orbits_used,
                f.orbits_total,
                t0.elapsed().as_secs_f64()
            )),
            None => out.push_str(&format!("  srg({v},{k},{l},{m}) {name}: not found in this language ({:.2} s)\n", t0.elapsed().as_secs_f64())),
        }
    }
    for &(v, k, l, m) in targets {
        out.push_str(&format!("\nsrg({v},{k},{l},{m}):\n"));
        let t0 = std::time::Instant::now();
        let (f, tried) = search(v, k, l, m, 200_000_000, 400, seconds);
        for t in &tried {
            out.push_str(&format!("  group {}: {} orbit systems searched, {} of them exhausted without a graph (the rest stopped at the node budget)\n", t.group, t.searched, t.exhausted));
        }
        match f {
            Some(f) => {
                let s: Vec<String> = f.set.iter().take(40).map(|x| format!("{:?}", f.group.coords(*x))).collect();
                out.push_str(&format!("  FOUND and checked at every vertex: Cayley graph on {}, {}, S ({} elements): {} ...\n", f.group.name(), f.how, f.set.len(), s.join(" ")));
            }
            None => out.push_str(&format!("  none found ({:.0} s); this rules out only the groups and multiplier groups exhausted above, nothing else\n", t0.elapsed().as_secs_f64())),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_the_small_known_graphs() {
        for &(v, k, l, m) in &[(9, 4, 1, 2), (13, 6, 2, 3), (16, 5, 0, 2)] {
            let (f, _) = search(v, k, l, m, 5_000_000, 30, 30.0);
            let f = f.unwrap_or_else(|| panic!("srg({v},{k},{l},{m})"));
            assert!(check_cayley(&f.group, &f.set, k, l, m));
        }
    }

    #[test]
    fn groups_of_an_order() {
        assert_eq!(abelian_groups(16).len(), 5);
        assert_eq!(abelian_groups(6273).len(), 2);
    }
}
